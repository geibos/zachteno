/** Тексты для `/login?oauth_error=<код>` после неудачного входа через Яндекс. */
const MESSAGES: Record<string, string> = {
	link_required:
		'Аккаунт с этим email уже есть. Войдите паролем и привяжите Яндекс ID в профиле.',
	state_mismatch: 'Сеанс входа устарел. Попробуйте войти ещё раз.',
	expired: 'Сеанс входа устарел. Попробуйте войти ещё раз.',
	denied: 'Вход через Яндекс отменён.',
	provider_error: 'Яндекс не ответил. Попробуйте ещё раз чуть позже или войдите по паролю.',
	no_email: 'Яндекс не передал email. Разрешите доступ к адресу почты или войдите по паролю.',
	already_linked: 'Этот Яндекс ID уже привязан к другой учётной записи.',
	blocked: 'Учётная запись заблокирована. Обратитесь к администратору.',
	internal: 'Не удалось войти через Яндекс. Попробуйте ещё раз.'
};

export function oauthErrorMessage(code: string | null | undefined): string | null {
	if (!code) return null;
	return MESSAGES[code] ?? 'Не удалось войти через Яндекс. Попробуйте ещё раз.';
}
